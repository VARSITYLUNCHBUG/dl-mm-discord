"""History tables are append-only, enforced by Postgres triggers.

Migrations are generated by `makemigrations` and never edited, so the triggers are installed here
instead, after every `migrate`. Each statement is idempotent: running it again changes nothing.
"""

from __future__ import annotations

from typing import Any

from django.db import connections

APPEND_ONLY_TABLES = (
    "rating_runs",
    "rating_events",
    "match_results",
    "match_transitions",
    "draft_actions",
    "draft_mode_versions",
    "match_awards",
    "strike_adjustments",
    "captain_overrides",
    "api_match_checks",
)

FUNCTION = """
CREATE OR REPLACE FUNCTION league_append_only() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION '% is append-only: % is not allowed', TG_TABLE_NAME, TG_OP
        USING ERRCODE = 'restrict_violation';
END;
$$ LANGUAGE plpgsql;
"""


def install_append_only_triggers(using: str = "default") -> None:
    connection = connections[using]
    if connection.vendor != "postgresql":
        return
    existing = set(connection.introspection.table_names())
    with connection.cursor() as cursor:
        cursor.execute(FUNCTION)
        for table in APPEND_ONLY_TABLES:
            if table not in existing:
                continue
            cursor.execute(f"DROP TRIGGER IF EXISTS {table}_append_only ON {table};")
            cursor.execute(
                f"CREATE TRIGGER {table}_append_only BEFORE UPDATE OR DELETE ON {table} "
                "FOR EACH ROW EXECUTE FUNCTION league_append_only();"
            )


def on_post_migrate(sender: Any, using: str = "default", **kwargs: Any) -> None:
    install_append_only_triggers(using)
